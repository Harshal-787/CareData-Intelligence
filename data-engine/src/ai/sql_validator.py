import sqlglot
from sqlglot import parse_one, exp
from typing import Tuple, List

class SQLValidator:
    """
    AST-based SQL validator to ensure queries generated by the LLM are safe to execute.
    It blocks destructive operations and ensures the query only accesses permitted tables.
    """
    
    def __init__(self, allowed_tables: List[str] = None):
        self.allowed_tables = allowed_tables or ["clinical_data", "clinical_encounters"]

    def validate_query(self, query: str) -> Tuple[bool, str]:
        """
        Parses the query into an Abstract Syntax Tree (AST) using sqlglot,
        and checks for safety.
        Returns: (is_safe, error_message)
        """
        try:
            # Parse the query. If it's invalid SQL, this will raise an exception.
            parsed = parse_one(query)
        except Exception as e:
            return False, f"SQL syntax error: {str(e)}"
            
        # 1. Ensure it's a SELECT statement (block DROP, DELETE, UPDATE, INSERT)
        if not isinstance(parsed, exp.Select):
            return False, "Only SELECT queries are allowed. Destructive operations are blocked."

        # 2. Check for unauthorized table access
        for table in parsed.find_all(exp.Table):
            table_name = table.name.lower()
            if table_name not in self.allowed_tables:
                return False, f"Unauthorized table access: '{table_name}'. Allowed tables are: {', '.join(self.allowed_tables)}"

        # 3. Ensure no dangerous function calls (e.g., file writing/reading if DuckDB allows it)
        # DuckDB has functions like read_csv, write_parquet, etc.
        for func in parsed.find_all(exp.Func):
            func_name = func.name.lower()
            dangerous_prefixes = ('read_', 'write_', 'copy', 'export')
            if func_name.startswith(dangerous_prefixes):
                return False, f"Function '{func_name}' is not allowed for security reasons."

        return True, "Query is safe."
